@lru_cache(maxsize=1)
def icons() -> dict:
    with gzip.open(HERE / "tabler.json.gz", "rt", encoding="utf-8") as f:
        return json.load(f)["icons"]


def search(query: str, n: int = 12) -> list[tuple[str, str, str]]:
    """Icons for some words: [(name, category, tags)], best first."""
    words = [w for w in re.findall(r"[a-z0-9]+", query.lower()) if w]
    if not words:
        return []
    scored = []
    for name, (cat, tags, _) in icons().items():
        parts = name.split("-")
        tagset = tags.lower().split()
        s = 0.0
        for w in words:
            if w == name:
                s += 10
            elif w in parts:
                s += 6 - 0.5 * parts.index(w)
            elif any(p.startswith(w) for p in parts):
                s += 3
            if w in tagset:
                s += 2.5
            elif any(t.startswith(w) for t in tagset):
                s += 1
            if w == cat.lower():
                s += 1
        if s:
            s -= 0.4 * (len(parts) - 1) + (2 if parts[-1] == "off" else 0)  # plain beats variants
            scored.append((s, name, cat, tags))
    scored.sort(key=lambda x: (-x[0], x[1]))
    return [(nm, c, t) for _, nm, c, t in scored[:n]]


def known(name: str) -> bool:
    return name in icons()


def suggest(name: str) -> str:
    hits = search(name.replace("-", " "), 4)
    return ", ".join(h[0] for h in hits) or "try: alvenus icons search WORDS"


# ------------------------------------------------------------------ SVG path -> points

_TOK = re.compile(r"[MmLlHhVvCcSsQqTtAaZz]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def _arc(x1, y1, rx, ry, phi, fa, fs, x2, y2):
    """Points along an SVG elliptical arc (endpoint form), per the SVG spec F.6.5."""
    if rx == 0 or ry == 0:
        return [(x2, y2)]
    rx, ry = abs(rx), abs(ry)
    c, s = math.cos(math.radians(phi)), math.sin(math.radians(phi))
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    x1p, y1p = c * dx + s * dy, -s * dx + c * dy
    lam = x1p ** 2 / rx ** 2 + y1p ** 2 / ry ** 2
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx ** 2 * ry ** 2 - rx ** 2 * y1p ** 2 - ry ** 2 * x1p ** 2
    den = rx ** 2 * y1p ** 2 + ry ** 2 * x1p ** 2
    k = math.sqrt(max(0.0, num / den)) if den else 0.0
    if fa == fs:
        k = -k
    cxp, cyp = k * rx * y1p / ry, -k * ry * x1p / rx
    cx, cy = c * cxp - s * cyp + (x1 + x2) / 2, s * cxp + c * cyp + (y1 + y2) / 2

    def ang(ux, uy, vx, vy):
        a = math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)
        return a

    t1 = ang(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry)
    dt = ang((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry)
    if not fs and dt > 0:
        dt -= 2 * math.pi
    elif fs and dt < 0:
        dt += 2 * math.pi
    n = max(4, int(abs(dt) * max(rx, ry) * 2.2))
    out = []
    for i in range(1, n + 1):
        t = t1 + dt * i / n
        out.append((cx + rx * math.cos(t) * c - ry * math.sin(t) * s, cy + rx * math.cos(t) * s + ry * math.sin(t) * c))
    return out


def _bez(p0, p1, p2, p3, n=12):
    return [((1 - t) ** 3 * p0[0] + 3 * (1 - t) ** 2 * t * p1[0] + 3 * (1 - t) * t ** 2 * p2[0] + t ** 3 * p3[0],
             (1 - t) ** 3 * p0[1] + 3 * (1 - t) ** 2 * t * p1[1] + 3 * (1 - t) * t ** 2 * p2[1] + t ** 3 * p3[1])
            for t in (i / n for i in range(1, n + 1))]


def path_points(d: str) -> list[tuple[list[tuple[float, float]], bool]]:
    """SVG path data -> [(points, closed)] in the icon's 24x24 units."""
    toks = _TOK.findall(d)
    subs: list[tuple[list, bool]] = []
    cur: list = []
    x = y = sx = sy = 0.0
    lastc = None  # last control point, for S and T
    cmd = None
    i = 0

    def num():
        nonlocal i
        v = float(toks[i])
        i += 1
        return v

    while i < len(toks):
        if re.fullmatch(r"[A-Za-z]", toks[i]):
            cmd = toks[i]
            i += 1
            if cmd in "Zz":
                if cur:
                    cur.append((sx, sy))
                    subs.append((cur, True))
                cur, x, y, lastc = [], sx, sy, None
                continue
        if cmd is None:
            break
        rel = cmd.islower()
        C = cmd.upper()
        ox, oy = (x, y) if rel else (0.0, 0.0)
        if C == "M":
            if cur:
                subs.append((cur, False))
            x, y = num() + ox, num() + oy
            sx, sy, cur, lastc = x, y, [(x, y)], None
            cmd = "l" if rel else "L"  # following pairs are lines
        elif C == "L":
            x, y = num() + ox, num() + oy
            cur.append((x, y))
            lastc = None
        elif C == "H":
            x = num() + ox
            cur.append((x, y))
            lastc = None
        elif C == "V":
            y = num() + oy
            cur.append((x, y))
            lastc = None
        elif C == "C":
            p1 = (num() + ox, num() + oy)
            p2 = (num() + ox, num() + oy)
            p3 = (num() + ox, num() + oy)
            cur += _bez((x, y), p1, p2, p3)
            x, y = p3
            lastc = p2
        elif C == "S":
            p1 = (2 * x - lastc[0], 2 * y - lastc[1]) if lastc else (x, y)
            p2 = (num() + ox, num() + oy)
            p3 = (num() + ox, num() + oy)
            cur += _bez((x, y), p1, p2, p3)
            x, y = p3
            lastc = p2
        elif C in "QT":
            if C == "Q":
                q = (num() + ox, num() + oy)
            else:
                q = (2 * x - lastc[0], 2 * y - lastc[1]) if lastc else (x, y)
            p3 = (num() + ox, num() + oy)
            p1 = (x + 2 / 3 * (q[0] - x), y + 2 / 3 * (q[1] - y))
            p2 = (p3[0] + 2 / 3 * (q[0] - p3[0]), p3[1] + 2 / 3 * (q[1] - p3[1]))
            cur += _bez((x, y), p1, p2, p3)
            x, y = p3
            lastc = q
        elif C == "A":
            rx, ry, phi, fa, fs = num(), num(), num(), num(), num()
            x2, y2 = num() + ox, num() + oy
            cur += _arc(x, y, rx, ry, phi, int(fa), int(fs), x2, y2)
            x, y = x2, y2
            lastc = None
        else:
            i += 1
    if cur:
        subs.append((cur, False))
    return subs


