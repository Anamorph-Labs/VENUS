def paint_for(sb: dict) -> tuple[str, str]:
    """(paint, accent) for a storyboard: from its design, style pack and accent colour."""
    from .presets import PRESETS

    style = sb.get("style") or ""
    p = PRESETS.get(style, {})
    accent = sb.get("accent") or p.get("accent") or "#FFD23F"
    design = sb.get("design") or p.get("design")
    if sb.get("picture_paint") in PAINTS:
        return sb["picture_paint"], accent
    if design == "mono":
        return "mono", accent
    if design == "paper":
        return "paper", accent
    if style == "archive-doc" or p.get("look") == "archive":
        return "archive", accent
    if style == "sepia-film" or p.get("look") == "sepia":
        return "sepia", accent
    if style == "talk-paper":
        return "light", accent
    if (sb.get("background") or p.get("background")) == "ink":
        return "ink", accent
    return "dark", accent


def _rgb(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


