def is_picture(v) -> bool:
    return isinstance(v, str) and v.startswith(PREFIXES)


def problem(spec: str) -> str | None:
    """What is wrong with a picture spec, in plain words (None when it is fine)."""
    if spec.startswith("scene:"):
        n = spec[6:].strip()
        return None if n in SCENES else f"{spec}: no drawn scene called {n!r}; choose one of {', '.join(SCENES)}"
    body = spec[5:].strip()
    names = [x.strip() for x in re.split(r"[+,>/]", body) if x.strip()]
    if not names:
        return f"{spec}: name an icon (alvenus icons search WORDS)"
    if len(names) > 5:
        return f"{spec}: at most five icons in one picture"
    for n in names:
        if n not in icons():
            return f"{spec}: no icon called {n!r}; close ones: {suggest(n)}"
    return None


def render(spec: str, w: int, h: int, paint: str = "dark", accent: str = "#FFD23F", seed: int = 7):
    """Draw a picture spec at w x h; returns a PIL image."""
    if why := problem(spec):
        raise SystemExit(why)
    p = Painter(paint, accent, w, h, seed)
    if spec.startswith("scene:"):
        _scene(p, spec[6:].strip())
        return p.done()
    body = spec[5:].strip()
    if "+" in body:
        a, b = [x.strip() for x in body.split("+", 1)]
        _hero(p, a, b)
    elif ">" in body:
        _row(p, [x.strip() for x in body.split(">")], arrows=True)
    elif "/" in body:
        a, b = [x.strip() for x in body.split("/", 1)]
        _versus(p, a, b)
    elif "," in body:
        _row(p, [x.strip() for x in body.split(",")], arrows=False)
    else:
        _hero(p, body)
    return p.done()


def size_for(aspect: str | None) -> tuple[int, int]:
    return {"9:16": (1080, 1920), "1:1": (1080, 1080), "4:5": (1080, 1350)}.get(aspect or "16:9", (1920, 1080))


def materialise(spec: str, sb: dict, cache: Path, seed: int = 7) -> Path:
    """Draw a picture once and keep it: the same spec in the same look is drawn only the first time."""
    paint, accent = paint_for(sb)
    w, h = size_for(sb.get("aspect"))
    if paint in ("paper", "mono"):  # designed looks print the picture on a card about this shape: fill the card
        w, h = 1080, 1350
    key = hashlib.sha256(json.dumps([spec, paint, accent, w, h, seed, VERSION]).encode()).hexdigest()[:16]
    out = cache / f"{re.sub(r'[^a-z0-9]+', '-', spec.lower()).strip('-')[:40]}-{key}.png"
    if not out.exists():
        cache.mkdir(parents=True, exist_ok=True)
        render(spec, w, h, paint, accent, seed).save(out)
    return out


def sheet(names: list[str], out: Path, paint: str = "light", accent: str = "#2B4A78") -> Path:
    """A contact sheet of icons with their names, for the AI (or the creator) to look at."""
    from PIL import ImageDraw

    from .paper import _font

    cols = min(6, max(1, len(names)))
    rows = math.ceil(len(names) / cols)
    cw, ch = 220, 230
    p = Painter(paint, accent, cols * cw, rows * ch)
    img = p.img.resize((cols * cw, rows * ch))
    d = ImageDraw.Draw(img)
    f = _font("DMMono-Regular.ttf", 15)
    for i, n in enumerate(names):
        cx, cy = (i % cols) * cw + cw / 2, (i // cols) * ch + ch / 2 - 14
        draw_icon(img, n, cx, cy, 120, PAINTS[paint][2], 1.6)
        d.text((cx, cy + 92), n, fill=PAINTS[paint][2], font=f, anchor="mm")
    img.save(out)
    return out


def board_sheet(sb: dict, out: Path) -> Path | None:
    """Every drawn picture in a loaded storyboard, numbered by scene, on one page: shown with the
    storyboard so the creator sees the pictures before saying yes."""
    from PIL import Image, ImageDraw

    from .paper import _font

    items = [(i, sc["_picture"], sc["file"]) for i, sc in enumerate(sb.get("scenes") or [], 1) if sc.get("_picture") and sc.get("file")]
    if not items:
        return None
    tw = 480
    first = Image.open(items[0][2])
    th = round(tw * first.height / first.width)
    cols = min(3, len(items))
    rows = math.ceil(len(items) / cols)
    page = Image.new("RGB", (cols * (tw + 16) + 16, rows * (th + 52) + 16), (246, 242, 234))
    d = ImageDraw.Draw(page)
    f = _font("DMMono-Regular.ttf", 17)
    for n, (i, spec, path) in enumerate(items):
        x, y = 16 + (n % cols) * (tw + 16), 16 + (n // cols) * (th + 52)
        page.paste(Image.open(path).convert("RGB").resize((tw, th), Image.LANCZOS), (x, y))
        d.text((x, y + th + 10), f"scene {i}  {spec}"[:44], fill=(34, 32, 29), font=f)
    page.save(out, quality=88)
    return out
