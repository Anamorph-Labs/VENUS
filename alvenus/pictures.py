def _hero(p: Painter, name: str, badge: str | None = None) -> None:
    if p.light:
        p.disc(0.54, 0.53, 0.25, "accent")
    else:
        p.disc(0.5, 0.5, 0.36, "glow", 0.55)
        p.ring(0.5, 0.5, 0.27, "accent", 0.005)
    p.icon(name, 0.5, 0.5, 0.42, "ink", 1.5, shadow=True)
    if badge:
        p.disc(0.71, 0.29, 0.1, "accent" if not p.light else "ink")
        p.icon(badge, 0.71, 0.29, 0.12, "bg", 2.0)


def _row(p: Painter, names: list[str], arrows: bool) -> None:
    n = len(names)
    if p.h > p.w * 1.2 and n > 2:  # tall frames: the steps go down the page
        gap = 1.5 / n
        size = min(0.3, gap * 0.6)
        for i, nm in enumerate(names):
            y = 0.5 - 0.75 + gap * (i + 0.5)
            if p.light:
                p.disc(0.5 + size * 0.08, y + size * 0.06, size * 0.62, "accent")
            else:
                p.disc(0.5, y, size * 0.9, "glow", 0.35)
            p.icon(nm, 0.5, y, size, "ink", 1.6, shadow=True)
            if arrows and i < n - 1:
                p.icon("arrow-narrow-down", 0.5, y + gap / 2, min(0.11, gap * 0.3), "accent", 1.8)
        return
    gap = 0.86 / n
    size = min(0.24, gap * 0.62)
    for i, nm in enumerate(names):
        x = 0.07 + gap * (i + 0.5)
        if p.light:
            p.disc(x + size * 0.08, 0.53, size * 0.62, "accent")
        else:
            p.disc(x, 0.5, size * 0.9, "glow", 0.35)
        p.icon(nm, x, 0.5, size, "ink", 1.6, shadow=True)
        if arrows and i < n - 1:
            p.icon("arrow-narrow-right", x + gap / 2, 0.5, min(0.09, gap * 0.3), "accent", 1.8)


def _versus(p: Painter, a: str, b: str) -> None:
    for x, nm in ((0.27, a), (0.73, b)):
        if p.light:
            p.disc(x + 0.02, 0.53, 0.15, "accent")
        else:
            p.disc(x, 0.5, 0.22, "glow", 0.4)
        p.icon(nm, x, 0.5, 0.26, "ink", 1.6, shadow=True)
    p.line(0.53, 0.3, 0.47, 0.7, "accent", 0.008)


