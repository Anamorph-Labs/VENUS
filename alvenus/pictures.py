"""Pictures without footage: icons and simple drawn scenes, in the video's own look.

When a creator has an idea but no clips or photos, every picture slot in a
storyboard ("file" of an image, clip, title, text, split side...) can name a
drawing instead of a file:

    "icon:battery"                 one icon, big, on a shape in the accent colour
    "icon:device-mobile+snowflake" a main icon with a small badge (a phone, and the cold)
    "icon:sun,cloud,cloud-rain"    a row of icons (things that go together)
    "icon:bulb>pencil>rocket"      a flow with arrows (steps, cause and effect)
    "icon:car/bike"                one against the other (a comparison)
    "scene:city"                   a small drawn scene (see SCENES)

The icons are the 5,000+ outline icons of Tabler Icons (MIT licence, bundled:
nothing is downloaded, nothing is generated by a paid AI). They are drawn
here, stroke by stroke, in the colours and paper of the style the video uses:
cream on dark for the dark looks, ink on paper (a little hand-made wobble) for
Vox paper, archive and sepia, ink on grey grid for mono.

Find icons with `alvenus icons search WORDS`; look at them with
`alvenus icons sheet NAMES --out sheet.png`; try a picture with
`alvenus picture "icon:..." --style vox-paper --out p.png`.
"""

