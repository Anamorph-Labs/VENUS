def draw_icon(img, name: str, cx: float, cy: float, size: float, colour, width: float = 2.0, rough: bool = False,
              seed: int = 0) -> None:
    """Draw one icon, centred, `size` pixels across, with round strokes (on an RGBA or RGB image)."""
    from PIL import ImageDraw

    if name not in icons():
        raise SystemExit(f"no icon called {name!r}; close ones: {suggest(name)}")
    d = ImageDraw.Draw(img)
    s = size / 24.0
    w = max(1.0, width * s)
    rng = _Rng(seed)
    for path in icons()[name][2]:
        for pts, closed in path_points(path):
            if not pts:
                continue
            xy = []
            for (px, py) in pts:
                jx = jy = 0.0
                if rough:  # a slow wobble, like a pen on paper
                    jx, jy = rng.wobble(px, py)
                xy.append((cx + (px - 12 + jx) * s, cy + (py - 12 + jy) * s))
            r = w / 2
            if len(xy) == 1:
                x0, y0 = xy[0]
                d.ellipse((x0 - r, y0 - r, x0 + r, y0 + r), fill=colour)
                continue
            d.line(xy, fill=colour, width=int(round(w)), joint="curve")
            for x0, y0 in (xy[0], xy[-1]) if not closed else ():
                d.ellipse((x0 - r, y0 - r, x0 + r, y0 + r), fill=colour)


class _Rng:
    def __init__(self, seed: int):
        self.a = (seed % 97) * 0.37 + 1.3

    def wobble(self, x: float, y: float) -> tuple[float, float]:
        a = self.a
        return (0.22 * math.sin(x * 0.9 + y * 0.4 + a) + 0.1 * math.sin(y * 2.3 + a * 2),
                0.22 * math.sin(y * 0.8 - x * 0.5 + a * 1.7) + 0.1 * math.sin(x * 2.1 + a))


def _canvas(paint: str, w: int, h: int, seed: int):
    """The ground: a soft gradient in the paint's colours, paper grain or film grain, a grid for mono."""
    import numpy as np
    from PIL import Image

    top, bot, ink, light, rough, grid = PAINTS[paint]
    yy = np.linspace(0, 1, h)[:, None, None]
    xx = np.linspace(-1, 1, w)[None, :, None]
    base = np.array(top, float) * (1 - yy) + np.array(bot, float) * yy
    vign = 1 - 0.10 * (xx ** 2) - 0.06 * ((yy - 0.45) * 2) ** 2
    img = base * (vign if not light else 1 - 0.04 * (xx ** 2))
    rng = np.random.default_rng(seed)
    img += rng.normal(0, 3.2 if light else 2.4, (h, w, 1))
    if light:  # paper fibres: low, wide noise
        small = rng.normal(0, 1, (h // 24 + 2, w // 24 + 2))
        big = np.array(Image.fromarray(((small - small.min()) / (np.ptp(small) + 1e-6) * 255).astype("uint8")).resize((w, h), Image.BICUBIC), float)
        img += ((big - 128) / 128 * 4.0)[:, :, None]
    out = Image.fromarray(np.clip(img, 0, 255).astype("uint8"), "RGB")
    if grid:
        from PIL import ImageDraw

        d = ImageDraw.Draw(out)
        step = max(24, min(w, h) // 18)
        col = tuple(int(c * 0.93) for c in top)
        for gx in range(step // 2, w, step):
            d.line((gx, 0, gx, h), fill=col, width=1)
        for gy in range(step // 2, h, step):
            d.line((0, gy, w, gy), fill=col, width=1)
    return out


def _disc(d, cx, cy, r, fill, rough=False, seed=0):
    if not rough:
        d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=fill)
        return
    pts = []
    a = (seed % 13) * 0.5
    for i in range(72):
        t = 2 * math.pi * i / 72
        rr = r * (1 + 0.035 * math.sin(3 * t + a) + 0.02 * math.sin(5 * t + 2 * a))
        pts.append((cx + rr * math.cos(t), cy + rr * math.sin(t)))
    d.polygon(pts, fill=fill)


def _glow(img, cx, cy, r, colour, alpha):
    from PIL import Image, ImageDraw, ImageFilter

    layer = Image.new("L", img.size, 0)
    ImageDraw.Draw(layer).ellipse((cx - r, cy - r, cx + r, cy + r), fill=int(255 * alpha))
    layer = layer.filter(ImageFilter.GaussianBlur(r * 0.45))
    img.paste(Image.new("RGB", img.size, colour), (0, 0), layer)


def _shadow(img, draw_fn, offset, blur, alpha):
    """A soft cast shadow under whatever draw_fn draws (the drawing floats a little off the page)."""
    from PIL import Image, ImageFilter

    m = Image.new("L", img.size, 0)
    draw_fn(m, 255)
    m = m.filter(ImageFilter.GaussianBlur(blur))
    m = m.point(lambda v: int(v * alpha))
    sh = Image.new("L", img.size, 0)
    sh.paste(m, (int(offset), int(offset)))
    img.paste(Image.new("RGB", img.size, (0, 0, 0)), (0, 0), sh)


class Painter:
    """Draws icons and shapes on a canvas in one paint, at 2x, then scales down for clean edges."""

    def __init__(self, paint: str, accent: str, w: int, h: int, seed: int = 7):
        from PIL import Image, ImageDraw

        self.paint, self.w, self.h, self.seed = paint, w, h, seed
        top, bot, ink, light, rough, grid = PAINTS[paint]
        self.ink, self.light, self.rough, self.bg = ink, light, rough, top
        self.accent = _rgb(accent)
        if paint in ("archive", "sepia", "mono") and paint != "mono":
            self.accent = self.accent
        self.S = 2
        self.img = _canvas(paint, w, h, seed).resize((w * 2, h * 2))
        self.d = ImageDraw.Draw(self.img)
        self.u = min(w, h) * 2  # the unit: the short side, at 2x
        self.ox = (w * 2 - self.u) / 2
        self.oy = (h * 2 - self.u) / 2
        self.Image = Image

    def at(self, x: float, y: float) -> tuple[float, float]:
        """Unit square (0..1, 0..1) -> pixels, centred on the frame."""
        spread = min(1.45, self.w / self.h) if self.w > self.h else 1.0  # wide frames: things spread out sideways
        return self.w + (x - 0.5) * self.u * spread, self.oy + y * self.u

    def icon(self, name: str, x: float, y: float, size: float, role: str = "ink", width: float = 1.6, shadow: bool = False):
        cx, cy = self.at(x, y)
        px = size * self.u
        col = {"ink": self.ink, "accent": self.accent, "bg": self.bg, "soft": self._soft()}[role]
        if shadow and not self.light:
            _shadow(self.img, lambda m, f: draw_icon(m, name, cx, cy, px, f, width, self.rough, self.seed), px * 0.025, px * 0.03, 0.55)
        draw_icon(self.img, name, cx, cy, px, col, width, self.rough, self.seed)

    def _soft(self):
        return tuple(int(a * 0.55 + b * 0.45) for a, b in zip(self.ink, self.bg))

    def disc(self, x: float, y: float, r: float, role: str = "accent", alpha: float = 1.0):
        cx, cy = self.at(x, y)
        R = r * self.u
        if role == "glow":
            return _glow(self.img, cx, cy, R, self.accent, alpha)
        col = {"accent": self.accent, "ink": self.ink, "soft": self._soft()}[role]
        if alpha < 1:
            from PIL import ImageDraw

            m = self.Image.new("L", self.img.size, 0)
            _disc(ImageDraw.Draw(m), cx, cy, R, int(255 * alpha), self.rough, self.seed)
            self.img.paste(self.Image.new("RGB", self.img.size, col), (0, 0), m)
        else:
            _disc(self.d, cx, cy, R, col, self.rough, self.seed)

    def ring(self, x, y, r, role="accent", width=0.006):
        cx, cy = self.at(x, y)
        R = r * self.u
        col = self.accent if role == "accent" else self.ink
        self.d.ellipse((cx - R, cy - R, cx + R, cy + R), outline=col, width=max(2, int(width * self.u)))

    def line(self, x0, y0, x1, y1, role="ink", width=0.006, full=False):
        col = {"accent": self.accent, "ink": self.ink, "soft": self._soft()}[role]
        if full:  # a line across the whole frame (the ground)
            _, py0 = self.at(0, y0)
            self.d.line((0, py0, self.w * 2, py0), fill=col, width=max(2, int(width * self.u)))
            return
        a, b = self.at(x0, y0), self.at(x1, y1)
        self.d.line((a, b), fill=col, width=max(2, int(width * self.u)))

    def dots(self, n, y0, y1, role="soft", seed=3):
        import random

        rnd = random.Random(seed)
        col = self.ink if role == "ink" else self._soft()
        for _ in range(n):
            x = rnd.uniform(0, self.w * 2)
            y = self.oy + rnd.uniform(y0, y1) * self.u
            r = rnd.uniform(1.2, 3.2) * self.S
            self.d.ellipse((x - r, y - r, x + r, y + r), fill=col)

    def done(self):
        return self.img.resize((self.w, self.h), self.Image.LANCZOS)


