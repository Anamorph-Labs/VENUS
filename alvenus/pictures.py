def _scene(p: Painter, name: str) -> None:
    if name not in SCENES:
        raise SystemExit(f"no drawn scene called {name!r}; choose one of {', '.join(SCENES)}")
    parts = SCENES[name]["parts"]
    glows = [(q[1], q[2], q[3]) for q in parts if q[0] == "glow"]
    for part in parts:
        if p.light and part[0] == "icon" and part[5] == "accent" and any(
                math.hypot(part[2] - gx, part[3] - gy) < gr for gx, gy, gr in glows):
            part = part[:5] + ("ink",)  # on paper the glow is an accent disc: the icon on it goes ink
        kind = part[0]
        if kind == "glow":
            if p.light:
                p.disc(part[1] + 0.02, part[2] + 0.02, part[3] * 0.75, "accent", 0.9)
            else:
                p.disc(part[1], part[2], part[3], "glow", 0.5)
        elif kind == "disc":
            p.disc(part[1], part[2], part[3], part[4], part[5])
        elif kind == "ground":
            p.line(0, part[1], 1, part[1], "soft" if not p.light else "ink", 0.005, full=True)
        elif kind == "dots":
            p.dots(part[1], part[2], part[3])
        elif kind == "icon":
            p.icon(part[1], part[2], part[3], part[4], part[5], 1.5, shadow=part[5] == "ink")


