def load(path: Path, data: dict | None = None) -> dict:
    """Read and check a storyboard. `data` is one already read (from a node
    file); file names in it are still taken from beside `path`."""
    if data is not None:
        sb = data
    else:
        try:
            sb = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            raise SystemExit(f"{path}: can't read the storyboard ({e})")
    base = path.parent
    problems = []
    for key in ("music", "voiceover"):
        if sb.get(key):
            sb[key] = str((base / sb[key]).resolve()) if not Path(sb[key]).is_absolute() else sb[key]
            if not Path(sb[key]).exists():
                problems.append(f"{key}: {sb[key]} not found")
    for i, sc in enumerate(sb.get("scenes") or []):
        kind = sc.get("type")
        if kind not in KINDS:
            problems.append(f"scene {i + 1}: type {kind!r} is not one of {', '.join(sorted(KINDS))}")
            continue
        for key in ("file", "image"):
            if sc.get(key):
                sc[key] = str((base / sc[key]).resolve()) if not Path(sc[key]).is_absolute() else sc[key]
                if not Path(sc[key]).exists():
                    problems.append(f"scene {i + 1}: {sc[key]} not found")
        for side in ("left", "right"):
            if isinstance(sc.get(side), dict) and sc[side].get("file"):
                f = sc[side]["file"]
                sc[side]["file"] = str((base / f).resolve()) if not Path(f).is_absolute() else f
                if not Path(sc[side]["file"]).exists():
                    problems.append(f"scene {i + 1}: {sc[side]['file']} not found")
        if kind in ("clip", "image", "archive") and not sc.get("file"):
            problems.append(f"scene {i + 1}: a {kind} scene needs \"file\"")
        if kind == "map" and not (sc.get("image") and sc.get("pins")):
            problems.append(f"scene {i + 1}: a map scene needs \"image\" and \"pins\"")
        if kind == "split" and not (sc.get("left", {}).get("file") and sc.get("right", {}).get("file")):
            problems.append(f"scene {i + 1}: a split scene needs left.file and right.file")
    for i, sc in enumerate(sb.get("scenes") or []):
        if sc.get("type") == "list" and not (isinstance(sc.get("items"), list) and 1 <= len(sc["items"]) <= 6):
            problems.append(f"scene {i + 1}: a list scene needs \"items\": 1 to 6 short lines")
        if sc.get("type") == "compare" and not all(isinstance(sc.get(k), dict) and sc[k].get("title") for k in ("left", "right")):
            problems.append(f"scene {i + 1}: a compare scene needs left and right, each {{\"title\": ..., \"points\": [...]}}")
        c = sc.get("callout")
        if c is not None and not (isinstance(c, dict) and 0 <= float(c.get("x", -1)) <= 1 and 0 <= float(c.get("y", -1)) <= 1 and c.get("label")):
            problems.append(f"scene {i + 1}: callout needs x and y (0 to 1, across and down the picture) and a label")
    from .archive import FRAMES

    for i, sc in enumerate(sb.get("scenes") or []):
        if sc.get("frame") and sc["frame"] not in FRAMES:
            problems.append(f"scene {i + 1}: frame {sc['frame']!r}: choose one of {', '.join(FRAMES)}")
        if sc.get("credit") and "|" not in str(sc["credit"]):
            problems.append(f"scene {i + 1}: credit is \"Role|Name\", e.g. \"Written by|Asha Rao\"")
    if sb.get("credits") is not None and not (isinstance(sb["credits"], list) and all(isinstance(c, (list, tuple)) and len(c) == 2 for c in sb["credits"])):
        problems.append("credits is a list of [role, name] pairs, one per scene from the start")
    if sb.get("quote_style") not in (None, "card", "verse"):
        problems.append("quote_style: choose card or verse")
    if not sb.get("scenes"):
        problems.append("no scenes")
    from .cut import TRANSITIONS
    from .presets import PRESETS
    from .style import TITLE_STYLES

    for key, allowed in (("transition", TRANSITIONS), ("title_style", TITLE_STYLES), ("style", PRESETS)):
        if sb.get(key) and sb[key] not in allowed:
            problems.append(f"{key} {sb[key]!r}: choose one of {', '.join(allowed)}")
    from .paper import CONTROLS, DESIGNS, control_problem

    if sb.get("design") and sb["design"] not in DESIGNS:
        problems.append(f"design {sb['design']!r}: choose one of {', '.join(DESIGNS)}")
    for i, sc in enumerate(sb.get("scenes") or []):
        for key in CONTROLS:
            if key in sc and (why := control_problem(key, sc[key])):
                problems.append(f"scene {i + 1}: {why}")
    from .paper import LAYERS, tool_problem

    for i, sc in enumerate(sb.get("scenes") or []):
        lay = sc.get("layers")
        if lay is not None and not (isinstance(lay, list) and set(lay) <= set(LAYERS) and len(set(lay)) == len(lay)):
            problems.append(f"scene {i + 1}: layers is a list, bottom to top, of {', '.join(LAYERS)}")
        tools = sc.get("tools")
        if tools is not None and not isinstance(tools, list):
            problems.append(f"scene {i + 1}: tools is a list of {{\"tool\": ..., \"on\": ...}}")
        for t in tools or []:
            if why := tool_problem(t):
                problems.append(f"scene {i + 1}: {why}")
    from .backgrounds import KINDS as BGS

    for i, sc in enumerate([sb] + list(sb.get("scenes") or [])):
        if sc.get("background") and sc["background"] not in BGS:
            problems.append(f"{'storyboard' if i == 0 else f'scene {i}'}: background {sc['background']!r}: choose one of {', '.join(BGS)}")
    for i, sc in enumerate(sb.get("scenes") or []):
        if sc.get("transition") and (sc["transition"] not in TRANSITIONS or sc["transition"] == "cut"):
            problems.append(f"scene {i + 1}: transition {sc['transition']!r}: choose one of {', '.join(t for t in TRANSITIONS if t != 'cut')}")
    if problems:
        raise SystemExit("storyboard problems:\n  " + "\n  ".join(problems))
    return sb


def _beat_snap(lengths: list[float], music: str | None) -> list[float]:
    """Move each scene boundary to the nearest beat (scenes stay at least 1.2 s)."""
    if not music:
        return lengths
    from .beats import beats_of

    beats = beats_of(Path(music), sum(lengths) + 5)
    if len(beats) < 4:
        return lengths
    out, t, prev = [], 0.0, 0.0
    for L in lengths:
        t += L
        near = min(beats, key=lambda b: abs(b - t))
        b = near if near - prev >= 1.2 else t
        out.append(round(b - prev, 3))
        prev = b
    return out


def _cover(w: int, h: int) -> str:
    return f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},setsar=1"


def _push(d: float, fps: float, amount: float) -> str:
    if not amount:
        return ""
    n = max(1, round(d * fps))
    z0, z1 = (1.0, 1 + amount) if amount > 0 else (1 - amount, 1.0)
    z = f"({z0:.4f}+{z1 - z0:.4f}*min(on/{n},1))"
    corners = [("W/2-W/2/", "H/2-H/2/"), ("W/2+W/2/", "H/2-H/2/"), ("W/2-W/2/", "H/2+H/2/"), ("W/2+W/2/", "H/2+H/2/")]
    return ",perspective=" + ":".join(f"x{i}='{a}{z}':y{i}='{b}{z}'" for i, (a, b) in enumerate(corners)) + ":interpolation=cubic:eval=frame"


def _scene_video(sc: dict, d: float, w: int, h: int, fps: float, out: Path, k: int) -> None:
    if sc.get("_design"):
        from .paper import scene_video

        return scene_video(sc, d, w, h, fps, out, sc.get("_k", k), sc.get("_total", 1))
    if sc["type"] == "archive":
        from .archive import scene_video as archive_video

        archive_video(sc, d, w, h, fps, out, sc.get("_k", k), sc.get("_accent", "#C0392B"))
    else:
        _plain_scene(sc, d, w, h, fps, out)
    if sc.get("frame"):
        from .archive import add_frame

        add_frame(out, sc["frame"], d, w, h, fps, sc.get("_k", k))
    from .paper import ff_tools, tools_on

    # node-graph tools on a plain scene work on its whole picture (it is one layer)
    tools = [t for b in ("background", "picture", "output") for t in tools_on(sc, b)]
    if tools:
        raw = out.with_name(out.stem + ".raw.mp4")
        out.rename(raw)
        g = ff_tools(tools, "0:v", "t", min(w, h), "tt") + ["[t]format=yuv420p[v]"]
        run(["ffmpeg", "-nostdin", "-y", "-v", "error", "-i", str(raw), "-filter_complex", ";".join(g), "-map", "[v]",
             "-an", "-c:v", "libx264", "-preset", "veryfast", "-crf", "14", "-pix_fmt", "yuv420p", str(out)])
        raw.unlink()


def _plain_scene(sc: dict, d: float, w: int, h: int, fps: float, out: Path) -> None:
    kind = sc["type"]
    base = ["ffmpeg", "-nostdin", "-y", "-v", "error"]
    enc = ["-t", f"{d:.3f}", "-an", "-c:v", "libx264", "-preset", "veryfast", "-crf", "14", "-pix_fmt", "yuv420p", "-r", f"{fps:g}", str(out)]
    media = sc.get("file") if kind in ("clip", "image", "title", "text", "quote", "stat") else None
    if kind == "split":
        L, R = sc["left"]["file"], sc["right"]["file"]
        vertical = h > w
        hw, hh = (w, h // 4 * 2) if vertical else (w // 4 * 2, h)  # even halves for 4:2:0 colour
        stack = "vstack" if vertical else "hstack"
        args = base
        for f in (L, R):
            args += (["-loop", "1"] if _still(f) else ["-ss", f"{float(sc.get('from', 0)):.3f}"]) + ["-t", f"{d + 0.2:.3f}", "-i", f]
        line = f"drawbox=x={'0' if vertical else 'iw-3'}:y={'ih-3' if vertical else '0'}:w={'iw' if vertical else 3}:h={3 if vertical else 'ih'}:color=white@0.9:t=fill"
        run(args + ["-filter_complex", f"[0:v]fps={fps:g},{_cover(hw, hh)}{_push(d, fps, 0.05)}[a];[1:v]fps={fps:g},{_cover(hw, hh)}{_push(d, fps, 0.05)},"
                    f"{line}[b];[a][b]{stack}=inputs=2,scale={w}:{h},setsar=1,format=yuv420p[v]", "-map", "[v]"] + enc)
        return
    if media:
        dim = kind in ("title", "text", "quote", "stat") and not sc.get("_verse")  # text over a picture: darken it so the words read
        dark = float(sc.get("darken", 0.22 if dim else 0.0))
        tail = f",eq=brightness=-{dark:.2f}:saturation=0.75,boxblur=6:1" if dim else (f",eq=brightness=-{dark:.2f}" if dark else "")
        push = float(sc.get("push", 0.06 if kind == "image" else 0.04 if kind == "clip" else 0.03))
        inp = (["-loop", "1"] if _still(media) else ["-ss", f"{float(sc.get('from', 0)):.3f}"]) + ["-t", f"{d + 0.2:.3f}", "-i", media]
        run(base + inp + ["-vf", f"fps={fps:g},{_cover(w, h)}{_push(d, fps, push)}{tail},format=yuv420p"] + enc)
        return
    # No footage: a living background made here (see backgrounds.py).
    from .backgrounds import source

    src, vf = source(sc.get("background") or sc.get("_bg") or "dark", w, h, fps, d + 0.2, sc.get("_accent", "#FFD23F"))
    dx = sc.get("_dir", 0)
    if dx:  # the background drifts against the camera's move: depth, like a filmed shot
        vf += (f",scale={round(w * 1.06) // 2 * 2}:{round(h * 1.06) // 2 * 2},"
               f"crop={w}:{h}:x='(iw-ow)/2*(1+{dx}*0.8*min(t/{d:.3f},1))':y='(ih-oh)/2'")
    run(base + ["-f", "lavfi", "-i", src, "-vf", vf] + enc)


def _scene_key(sc: dict, d: float, w: int, h: int, fps: float) -> str:
    """Everything that changes a scene's picture: its settings (but not its
    words, which are drawn later over the whole video), its length, the frame,
    and the files it uses as they are now."""
    import hashlib

    from . import media

    words = {"text", "caption", "label", "items", "title", "who", "value", "points", "callout", "big_words", "pins", "bars",
             "subtitle", "note", "year", "tag", "detail", "credit"}
    keep = {k: v for k, v in sc.items() if k not in words and k != "_k" and not k.startswith(("words_", "mark_"))
            and not (sc["type"] == "compare" and k in ("left", "right"))}
    if sc.get("_design"):
        from .paper import inside

        if inside(sc):  # its words are drawn into the scene itself (the node graph put something over them)
            keep = {k: v for k, v in sc.items() if k != "_k"}
    if sc["type"] in ("map",):  # a map's pins are drawn later too, but its picture is the image
        keep["image"] = sc.get("image")
    stamps = []
    for f in [sc.get("file"), sc.get("image"), (sc.get("left") or {}).get("file") if isinstance(sc.get("left"), dict) else None,
              (sc.get("right") or {}).get("file") if isinstance(sc.get("right"), dict) else None]:
        if f and Path(f).exists():
            st = Path(f).stat()
            stamps.append((f, st.st_size, st.st_mtime_ns))
    if sc.get("_design"):
        from .paper import VERSION, has_words

        keep["_design_v"] = VERSION
        keep["_has_words"] = has_words(sc)
        keep["_k"] = sc.get("_k")  # the scene's place picks its shape and paper
    blob = json.dumps([keep, round(d, 3), w, h, fps, media.DRAFT, stamps, 1], sort_keys=True, default=str)
    return hashlib.sha256(blob.encode()).hexdigest()[:16]


def build(sb: dict, out: Path, size: str, fps: float = 30.0) -> list[str]:
    from .cut import TRANSITIONS, join_pair
    from .finish import finish
    from .graphics import Chart, MapCard, Pin, Quote, Stat, Timeline
    from .wordtime import Word

    w, h = (int(x) for x in size.split("x"))
    scenes = sb["scenes"]
    moving = sb.get("camera", True)
    for k, sc in enumerate(scenes):  # what a footage-free scene is drawn on, and which way its camera drifts
        sc["_bg"], sc["_accent"] = sb.get("background", "dark"), sb.get("accent", "#FFD23F")
        footage = sc.get("file") or sc["type"] in ("clip", "image", "map", "split", "archive")
        sc["_dir"] = 0 if footage or not moving else (1 if k % 2 == 0 else -1)
        sc["_verse"] = sc["type"] == "quote" and (sc.get("style") or sb.get("quote_style")) == "verse"
    design = sb.get("design")
    for k, sc in enumerate(scenes):
        # its place in the whole video (a scene built alone with --scene keeps its own)
        at, of = sb.get("_place") or (k, len(scenes))
        sc["_design"], sc["_total"], sc["_k"] = design, of, at
        if design:
            from .paper import plain

            if design == "mono":  # the page furniture prints the video's name and this scene's own words
                first = next((x for x in scenes if x["type"] == "title" and x.get("text")), None)
                sc["_label"] = sb.get("label") or (plain(first["text"]) if first else "")
                sc["_words"] = plain(sc.get("text") or sc.get("caption") or "")
            sc["_dir"] = 0  # designed scenes move their own layers
    lengths = [float(sc.get("seconds", 3.0)) for sc in scenes]
    if sb.get("cut_on_beat", True):
        lengths = _beat_snap(lengths, sb.get("music"))
    trans = sb.get("transition", "crossfade")
    td = float(sb.get("transition_seconds", 0.4)) if TRANSITIONS.get(trans) else 0.0
    td = min(td, min(lengths) / 3)
    sb["_why"] = {"asked": [float(sc.get("seconds", 3.0)) for sc in scenes], "got": lengths,
                  "beat": bool(sb.get("music") and sb.get("cut_on_beat", True)), "trans": trans, "td": td}
    starts = [sum(lengths[:i]) for i in range(len(lengths))]
    for sc, L in zip(scenes, lengths):
        sc["_len"] = L  # the scene's own length (its video runs on under the next transition)
    total = sum(lengths)
    tmp = Path(tempfile.mkdtemp(prefix="alvenus-s-", dir=out.parent))
    notes: list[str] = []
    try:
        seg = [L + (td if i < len(scenes) - 1 else 0.0) for i, L in enumerate(lengths)]
        # Each scene's picture is kept, keyed by everything that shapes it, so
        # changing one scene (or only words, sound or titles) redraws only that one.
        cache = out.parent / ".venus-cache" / out.stem
        cache.mkdir(parents=True, exist_ok=True)
        keys = [_scene_key(scenes[i], seg[i], w, h, fps) for i in range(len(scenes))]
        todo = [i for i in range(len(scenes)) if not (cache / f"{keys[i]}.mp4").exists()]
        with ThreadPoolExecutor(max(1, min(3, (os.cpu_count() or 2) - 1))) as pool:
            list(pool.map(lambda i: _scene_video(scenes[i], seg[i], w, h, fps, cache / f"{keys[i]}.mp4", i), todo))
        for f in cache.glob("*.mp4"):  # only the current version of each scene is kept
            if f.stem not in keys:
                f.unlink()
        files = [cache / f"{k}.mp4" for k in keys]
        sb["_redrawn"] = todo
        # Join with transitions; the sound bed is the voiceover, or silence.
        args = ["ffmpeg", "-nostdin", "-y", "-v", "error"]
        for f in files:
            args += ["-i", str(f)]
        parts, prev = [], "0:v"
        for i in range(1, len(files)):
            o = "vj" if i == len(files) - 1 else f"x{i}"
            if td:
                parts.append(join_pair(prev, f"{i}:v", o, scenes[i].get("transition", trans), td, starts[i], f"{w}x{h}", fps, i))
            else:
                parts.append(f"[{prev}][{i}:v]concat=n=2:v=1[{o}]")
            prev = o
        if len(files) == 1:
            parts.append("[0:v]null[vj]")
        vo = sb.get("voiceover")
        if vo:
            args += ["-i", vo]
            parts.append(f"[{len(files)}:a]aformat=sample_rates=48000:channel_layouts=stereo,apad,atrim=0:{total:.3f}[aj]")
        else:
            # no voice and no music: a faint room hiss, so players and platforms
            # don't meet dead digital silence (the effects still sit on top)
            src = "anullsrc=r=48000:cl=stereo" if sb.get("music") else "anoisesrc=c=pink:a=0.0012:r=48000"
            args += ["-f", "lavfi", "-t", f"{total:.3f}", "-i", src]
            parts.append(f"[{len(files)}:a]aformat=sample_rates=48000:channel_layouts=stereo[aj]")
        base = out.with_name(out.stem + ".base.mp4")
        run(args + ["-filter_complex", ";".join(parts), "-map", "[vj]", "-map", "[aj]", "-t", f"{total:.3f}",
                    "-c:v", "libx264", "-preset", "veryfast", "-crf", "14", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "192k", str(base)])
    finally:
        for f in tmp.glob("*"):
            f.unlink()
        tmp.rmdir()

    # Every scene is a "line" of the finishing pass: graphics, captions,
    # sound effects and music all hang off where each scene sits.
    spans = {i: (starts[i], starts[i] + lengths[i]) for i in range(len(scenes))}
    sb["_spans"] = spans  # where each scene sits, for the self-review's fixes
    words, all_words, stats, charts, lcharts, quotes, maps, tls, kinetic, titles = [], [], [], [], [], [], [], [], [], []

    def spread(text: str, line: int, t0: float, t1: float, fill: float = 0.75):
        ws = text.split()
        step = (t1 - t0) * fill / max(1, len(ws))
        return [Word(x, t0 + 0.15 + k * step, t0 + 0.15 + (k + 1) * step, line) for k, x in enumerate(ws)]

    designed: list[str] = []
    beats: list[float] = []
    verses: list = []
    archive: list = []
    for i, sc in enumerate(scenes):
        if design and sc["type"] in ("title", "text", "clip", "image"):
            from .paper import scene_events

            from .paper import inside

            ev, b = scene_events(sc, sc["_k"], *spans[i], w, h, sc["_total"])
            if not inside(sc):  # (else they are already in the scene's own picture)
                designed += ev
            beats += b
    sb["_beats"] = beats
    for i, sc in enumerate(scenes):
        t0, t1 = spans[i]
        kind = sc["type"]
        if design and kind in ("title", "text", "clip", "image"):
            continue
        if not design:  # *word* / ==word== / _word_ belong to the designed looks; elsewhere the marked words become big words
            from .paper import parse, plain

            marked = [w for k in ("text", "caption") for w, r in parse(str(sc.get(k) or ""), set()) if r in ("serif", "mark")]
            if marked and kind == "text":
                sc = {**sc, "big_words": list(sc.get("big_words") or []) + [re.sub(r"[^\w']", "", m) for m in marked]}
            sc = {**sc, **{k: plain(str(sc[k])) for k in ("text", "caption") if sc.get(k)}}
        if sc.get("caption") and sb.get("captions", True):
            words += spread(sc["caption"], i, t0, t1)
        if kind == "title":
            titles.append((sc.get("text", ""), t0, t1))
        elif kind == "text":
            ws = spread(sc.get("text", ""), i, t0, t1, 0.6)
            all_words += ws
            kinetic.append((i, {re.sub(r"[^\w']", "", x.lower()) for p in sc.get("big_words") or [] for x in str(p).split()} - {""}))
        elif kind == "stat":
            stats.append(Stat(i, str(sc.get("value", "")), sc.get("label", "")))
        elif kind == "chart":
            charts.append(Chart(i, [(str(a), float(b)) for a, b in sc.get("bars", [])], sc.get("title", "")))
        elif kind == "line_chart":
            lcharts.append(Chart(i, [(str(a), float(b)) for a, b in sc.get("points", [])], sc.get("title", "")))
        elif kind == "quote" and (sc.get("style") or sb.get("quote_style")) == "verse":
            verses.append((sc.get("text", ""), sc.get("who", ""), t0 + (td * 0.8 if i else 0), t1))  # words wait for the reveal
        elif kind == "quote":
            quotes.append(Quote(i, sc.get("who", ""), sc.get("text", "")))
        elif kind == "archive":
            archive.append((str(sc.get("year", "")), str(sc.get("tag", "")), str(sc.get("detail", "")), t0 + (td * 0.8 if i else 0), t1, sc.get("_k", i)))
        elif kind == "timeline":
            tls.append(Timeline(i, [(str(a), str(b)) for a, b in sc.get("items", [])], sc.get("title", "")))
        elif kind == "map":
            maps.append(MapCard(i, sc["image"], [Pin(float(p["x"]), float(p["y"]), p.get("label", "")) for p in sc["pins"]],
                                bool(sc.get("route", True))))
    from .graphics import callout_events, compare_events, list_events

    more, pops = list(designed), []
    for i, sc in enumerate(scenes):
        t0, t1 = spans[i]
        if sc["type"] == "list":
            more += list_events(sc.get("title", ""), [str(x) for x in sc["items"]], t0, t1, w, h, sb.get("accent", "#FFD23F"))
            n = len(sc["items"])
            pops += [t0 + 0.35 + max(0.6, (t1 - t0) - 0.9) * k / n for k in range(n)]
        elif sc["type"] == "compare":
            side = lambda d: (str(d["title"]), [str(x) for x in d.get("points") or []])
            more += compare_events(side(sc["left"]), side(sc["right"]), t0, t1, w, h, sb.get("accent", "#FFD23F"))
            pops += [t0 + 0.3, t0 + 0.3 + min(1.2, (t1 - t0) * 0.3)]
        if sc.get("callout") and not (design and sc["type"] in ("clip", "image", "title", "text")):
            c = sc["callout"]
            more += callout_events(float(c["x"]), float(c["y"]), str(c["label"]), t0, t1, w, h, sb.get("accent", "#FFD23F"))
            pops.append(t0 + 0.8)
    lower = []
    for i, sc in enumerate(scenes):
        if sc["type"] == "split":
            for side in ("left", "right"):
                if sc[side].get("label"):
                    lower.append((i, side, sc[side]["label"]))
    sfx = [(starts[i] + td / 2, "whoosh") for i in range(1, len(scenes))] if trans in ("whip", "slide", "zoom", "flash", "circle", "glitch") else []
    sfx += [(t, "pop") for t in pops]
    from . import graphics

    graphics.PANELS = False  # the scene's own background shows behind charts, numbers and quotes
    from . import genre

    genre.EXTRAS = {k: sb[k] for k in ("letterbox", "datestamp", "lower_third_style") if sb.get(k)}
    if genre.EXTRAS.get("letterbox") in (True, "true", "on"):
        genre.EXTRAS["letterbox"] = 2.39
    elif "letterbox" in genre.EXTRAS:
        genre.EXTRAS["letterbox"] = float(genre.EXTRAS["letterbox"])
    places = [(str(sc["place"]), spans[i][0] + 0.2, max(spans[i][1], spans[i][0] + 3.5)) for i, sc in enumerate(scenes) if sc.get("place")]
    arrivals = [(str(sc["arrive"]), spans[i][0] + 0.05, min(spans[i][1] + 0.6, spans[i][0] + 2.8)) for i, sc in enumerate(scenes) if sc.get("arrive")]
    if places:
        genre.EXTRAS["places"] = places
    if arrivals:
        genre.EXTRAS["arrivals"] = arrivals
    credits = [tuple(str(x) for x in c) for c in sb.get("credits") or []]
    credit_rows = []
    for i, sc in enumerate(scenes):
        role_name = str(sc["credit"]).split("|", 1) if sc.get("credit") else (credits[i] if i < len(credits) else None)
        if role_name:
            t0, t1 = spans[i]
            credit_rows.append((role_name[0].strip(), role_name[1].strip(), t0 + min(0.5, (t1 - t0) * 0.15), t1 - 0.1))
    for key, val in (("archive", archive), ("verses", verses), ("credits", credit_rows)):
        if val:
            genre.EXTRAS[key] = val
    try:
        notes += finish(base, out, size, fps, spans, music=Path(sb["music"]) if sb.get("music") else None,
                        music_lufs=float(sb.get("music_lufs", -16.0 if not sb.get("voiceover") else -22.0)),
                        end_card=sb.get("end_card"), card_len=float(sb.get("end_card_seconds", 2.5)), words=words or None, look=sb.get("look", "natural"),
                        accent=sb.get("accent", "#FFD23F"), all_words=all_words, stats=stats, charts=charts,
                        sfx=None if sb.get("sound_effects") is False else sfx, line_charts=lcharts, quotes=quotes,
                        progress=bool(sb.get("progress")), scene_marks=starts[1:], maps=maps, timelines=tls,
                        kinetic_lines=kinetic, titles=titles, title_style=sb.get("title_style", "track"), more_events=more, camera=[spans[i] for i, sc in enumerate(scenes) if sc["_dir"]],
                        split_labels=[(spans[i], side, lab) for i, side, lab in lower])
    finally:
        graphics.PANELS = True
        genre.EXTRAS = {}
    base.unlink()
    return notes


def autofix(sb: dict, findings, frozen: set[str] = frozenset()) -> list[str]:
    """Change the storyboard so the problems the self-review found go away:
    text too quick to read gets a longer scene, text that is hard to read gets
    a darker picture behind it, flashing transitions become dissolves. Returns
    what was changed, in plain words ([] = nothing left that can be fixed).
    `frozen` holds what must not change ("3:seconds" = scene 4's length,
    "end_card_seconds"): the parts the person locked."""
    spans = sb.get("_spans") or {}
    scenes = sb["scenes"]
    if not spans:
        return []
    end = max(t1 for _, t1 in spans.values())

    def scene_at(t: float) -> int | None:
        return next((i for i, (a, b) in spans.items() if a - 0.05 <= t < b), None)

    done: list[str] = []
    for f in findings:
        kind = getattr(f, "kind", None)
        for t in getattr(f, "times", [])[:12]:
            if kind == "reading":
                more = round(f.extra["need"] - f.extra["shown"] + 0.4, 1)
                if t >= end - 0.05 and sb.get("end_card") and "end_card_seconds" not in frozen:
                    sb["end_card_seconds"] = round(float(sb.get("end_card_seconds", 2.5)) + more, 1)
                    done.append(f"end card held {more}s longer")
                elif (i := scene_at(t)) is not None and float(scenes[i].get("seconds", 3.0)) < 12 and f"{i}:seconds" not in frozen:
                    scenes[i]["seconds"] = round(spans[i][1] - spans[i][0] + more, 1)
                    done.append(f"scene {i + 1} lengthened to {scenes[i]['seconds']}s so its text can be read")
            elif kind == "contrast":
                i = scene_at(t)
                if i is None or scenes[i].get("type") not in ("clip", "image", "title", "text", "quote", "stat", "split") or f"{i}:darken" in frozen:
                    continue
                cur = float(scenes[i].get("darken", 0.22 if scenes[i]["type"] in ("title", "text", "quote", "stat") else 0.0))
                if cur < 0.45 and not any(d.startswith(f"scene {i + 1} darkened") for d in done):
                    scenes[i]["darken"] = round(min(0.45, cur + 0.15), 2)
                    done.append(f"scene {i + 1} darkened behind its text")
            elif kind == "flash":
                near = min(range(1, len(scenes)), key=lambda j: abs(spans[j][0] - t), default=None)
                if near is not None and abs(spans[near][0] - t) < 1.0 and scenes[near].get("transition", sb.get("transition")) in ("glitch", "flash") \
                        and f"{near}:transition" not in frozen:
                    scenes[near]["transition"] = "crossfade"
                    done.append(f"scene {near + 1} now dissolves in instead of flashing")
    return list(dict.fromkeys(done))


WHAT = {
    "title": "a title card", "text": "one strong line as moving type", "stat": "one number that counts up",
    "chart": "bars comparing things", "line_chart": "a line showing change over time", "quote": "someone's words",
    "timeline": "dated moments in order", "map": "a map with pins", "split": "two pictures side by side",
    "list": "points that arrive one at a time", "compare": "two sides, one after the other", "clip": "footage",
    "image": "a still picture with a slow move",
}


def explain(sb: dict) -> str:
    """Why the video is cut the way it is, scene by scene, in plain words: the
    note a good editor leaves so the creator can disagree with something specific."""
    why, spans, scenes = sb.get("_why") or {}, sb.get("_spans") or {}, sb["scenes"]
    out = ["# Why it is cut this way", ""]
    trans = why.get("trans", "crossfade")
    out.append(f"Scenes change with {'an' if trans[0] in 'aeiou' else 'a'} {trans}" + (f" of {why.get('td', 0):.1f} s" if why.get("td") else "")
               + (", and every change lands on a beat of the music." if why.get("beat") else "."))
    out.append("")
    for i, sc in enumerate(scenes):
        a, b = spans.get(i, (0.0, 0.0))
        asked, got = why.get("asked", [0] * len(scenes))[i], b - a
        bits = [f"**{i + 1}. {sc['type']}** ({a:.1f} to {b:.1f} s): {WHAT.get(sc['type'], sc['type'])}"]
        words = len(" ".join(str(sc.get(k, "")) for k in ("text", "caption", "label", "title", "who")).split())
        words += sum(len(str(x).split()) for x in sc.get("items") or [])
        for side in ("left", "right"):
            if sc["type"] == "compare" and isinstance(sc.get(side), dict):
                words += len(" ".join([str(sc[side].get("title", ""))] + [str(x) for x in sc[side].get("points") or []]).split())
        words += len(str((sc.get("callout") or {}).get("label", "")).split())
        if i == 0 and got <= 2.7:
            bits.append("the hook: it is over inside the first few seconds, before a viewer decides to scroll")
        if abs(got - asked) > 0.05:
            bits.append(f"{asked:g} s asked, {got:.1f} s used so the cut falls on the beat" if why.get("beat")
                        else f"{asked:g} s asked, {got:.1f} s used")
        if words:
            need = 0.5 + 0.28 * words
            bits.append(f"{words} words on screen need about {need:.1f} s to read" + (" (tight)" if need > got - 0.2 else ""))
        if sc.get("callout"):
            bits.append(f"a callout points at \"{sc['callout'].get('label', '')}\"")
        if sc.get("transition"):
            bits.append(f"comes in with a {sc['transition']} of its own")
        out.append("- " + "; ".join(bits) + ".")
    return "\n".join(out) + "\n"
